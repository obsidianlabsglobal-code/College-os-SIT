#!/usr/bin/env python3
"""Generate docs/NEXUS_TRACEABILITY_MATRIX.md from the canonical registry.

Audit classes follow the founder vocabulary. A registry "Tested" row counts as "Functionally tested (local)"
only when a test file annotated `// covers: <ID>` passed in docs/evidence/test-run.json (recorded per file
with its commit by scripts/record-test-run.py). A Tested claim with no linked passing test is reported as
such, not trusted. Qualified rows ("Tested (in-app only)") stay partial. Nothing is hosted or user-validated.
"""
import collections, glob, json, os, re

covers = collections.defaultdict(set)
for path in sorted(glob.glob("tests/**/*.ts", recursive=True)):
    for line in open(path, encoding="utf8"):
        m = re.match(r"\s*//\s*covers:\s*(.+)", line)
        if m:
            for rid in re.findall(r"[A-Z]+-\d{3}", m.group(1)):
                covers[rid].add(path)
run = json.load(open("docs/evidence/test-run.json")) if os.path.exists("docs/evidence/test-run.json") else {"commit": "none", "files": {}}
def passing(rid):
    files = sorted(covers.get(rid, ()))
    ok = [f for f in files if run["files"].get(f, {}).get("passed", 0) > 0 and run["files"][f].get("failed", 0) == 0]
    return files, ok
rows, domain = [], ""
for line in open("docs/NEXUS_MASTER_FEATURE_REGISTRY.md", encoding="utf8"):
    if line.startswith("## "):
        domain = line[3:].strip()
    m = re.match(r"\| ([A-Z]+-\d{3}) \| (.*?) \| (.*?) \| (.*?) \| (.*?) \|\s*$", line)
    if m:
        rows.append((domain, *m.groups()))

def classify(status, rid=None):
    files, ok = passing(rid)
    if status.startswith("Tested ("):
        return "Partially implemented" if ok else "Tested claim without linked evidence"
    if status == "Tested":
        return "Functionally tested (local)" if ok and len(ok) == len(files) else "Tested claim without linked evidence"
    if status in ("Implemented", "In development"):
        return "Implemented but unverified" if status == "Implemented" else "Partially implemented"
    if status == "Blocked":
        return "Blocked by an actual dependency"
    return "Missing"

counts = collections.Counter(classify(r[4], r[1]) for r in rows)
by_domain = collections.defaultdict(collections.Counter)
for r in rows:
    by_domain[r[0]][classify(r[4], r[1])] += 1
order = ["Functionally tested (local)", "Tested claim without linked evidence", "Implemented but unverified", "Partially implemented",
         "Blocked by an actual dependency", "Missing", "Hosted and verified", "User-validated"]
out = ["# NEXUS traceability matrix", "",
       "Generated by `python3 scripts/traceability.py` from `docs/NEXUS_MASTER_FEATURE_REGISTRY.md`, test annotations (`// covers: ID`)",
       f"and the recorded run `docs/evidence/test-run.json` (commit {run['commit'][:7]}, {run.get('recorded_at', 'not recorded')}, {run.get('environment', '')}).",
       "\"Functionally tested (local)\" means every test file linked to that ID passed in the recorded run. It is not hosted or institutional",
       "validation. \"Tested claim without linked evidence\" means the registry says Tested but no annotated passing test supports it yet.",
       "No row is Hosted and verified, Visually accepted or User-validated.", "",
       "## Summary", "", "| Class | Count |", "| --- | --- |"]
out += [f"| {k} | {counts.get(k, 0)} |" for k in order] + [f"| **Total** | **{len(rows)}** |", ""]
out += ["## By domain", "", "| Domain | " + " | ".join(order[:6]) + " |", "| --- |" + " --- |" * 6]
for d, c in by_domain.items():
    out.append(f"| {d} | " + " | ".join(str(c.get(k, 0)) for k in order[:6]) + " |")
out += ["", "## Every registry ID", "", "| ID | Capability | Registry status | Audit class | Linked tests (passing in recorded run) | Registry evidence |", "| --- | --- | --- | --- | --- | --- |"]
for d, i, cap, _, status, ev in rows:
    files, ok = passing(i)
    linked = ", ".join(f"`{f}`" + ("" if f in ok else " (not passing)") for f in files) or "—"
    out.append(f"| {i} | {cap} | {status} | {classify(status, i)} | {linked} | {ev} |")
open("docs/NEXUS_TRACEABILITY_MATRIX.md", "w", encoding="utf8").write("\n".join(out) + "\n")
print(len(rows), dict(counts))
