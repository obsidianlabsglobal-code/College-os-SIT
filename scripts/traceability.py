#!/usr/bin/env python3
"""Generate docs/NEXUS_TRACEABILITY_MATRIX.md from the canonical registry.

Audit classes follow the founder vocabulary. A registry "Tested" row is only counted as
"Functionally tested" when the local suites that carry its evidence pass on the audited commit;
qualified rows ("Tested (whole section)") are partial. Nothing is hosted or user-validated.
"""
import collections, re, sys

PASSED_SUITES = len(sys.argv) > 1 and sys.argv[1] == "--suites-passed"
rows, domain = [], ""
for line in open("docs/NEXUS_MASTER_FEATURE_REGISTRY.md", encoding="utf8"):
    if line.startswith("## "):
        domain = line[3:].strip()
    m = re.match(r"\| ([A-Z]+-\d{3}) \| (.*?) \| (.*?) \| (.*?) \| (.*?) \|\s*$", line)
    if m:
        rows.append((domain, *m.groups()))

def classify(status):
    if status.startswith("Tested ("):
        return "Partially implemented"
    if status == "Tested":
        return "Functionally tested (local)" if PASSED_SUITES else "Implemented but unverified"
    if status in ("Implemented", "In development"):
        return "Implemented but unverified" if status == "Implemented" else "Partially implemented"
    if status == "Blocked":
        return "Blocked by an actual dependency"
    return "Missing"

counts = collections.Counter(classify(r[4]) for r in rows)
by_domain = collections.defaultdict(collections.Counter)
for r in rows:
    by_domain[r[0]][classify(r[4])] += 1
order = ["Functionally tested (local)", "Implemented but unverified", "Partially implemented",
         "Blocked by an actual dependency", "Missing", "Hosted and verified", "User-validated"]
out = ["# NEXUS traceability matrix", "",
       "Generated by `python3 scripts/traceability.py --suites-passed` from `docs/NEXUS_MASTER_FEATURE_REGISTRY.md`.",
       "Audit date 2026-11-27, commit c0902ae. See [engineering audit](NEXUS_ENGINEERING_AUDIT.md) for method and evidence.",
       "\"Functionally tested (local)\" means the registry row's evidence suites passed on a fresh local database in this audit;",
       "it is not hosted or institutional validation. No row is Hosted and verified or User-validated.", "",
       "## Summary", "", "| Class | Count |", "| --- | --- |"]
out += [f"| {k} | {counts.get(k, 0)} |" for k in order] + [f"| **Total** | **{len(rows)}** |", ""]
out += ["## By domain", "", "| Domain | " + " | ".join(order[:5]) + " |", "| --- |" + " --- |" * 5]
for d, c in by_domain.items():
    out.append(f"| {d} | " + " | ".join(str(c.get(k, 0)) for k in order[:5]) + " |")
out += ["", "## Every registry ID", "", "| ID | Capability | Registry status | Audit class | Registry evidence |", "| --- | --- | --- | --- | --- |"]
for d, i, cap, _, status, ev in rows:
    out.append(f"| {i} | {cap} | {status} | {classify(status)} | {ev} |")
open("docs/NEXUS_TRACEABILITY_MATRIX.md", "w", encoding="utf8").write("\n".join(out) + "\n")
print(len(rows), dict(counts))
