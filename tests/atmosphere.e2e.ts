import { expect, test } from "@playwright/test";
import { demoEmail, demoPassword } from "../scripts/fixtures";

test("mobile themes, scoped More menu and a confirmed direct academic lookup", async ({page}) => {
  await page.setViewportSize({width:320,height:720});
  await page.emulateMedia({colorScheme:"dark",reducedMotion:"reduce"});
  await page.goto("/login");
  await page.getByLabel("Email").fill(demoEmail("student"));
  await page.getByLabel("Password").fill(demoPassword);
  await page.getByRole("button",{name:"Sign in"}).click();
  await expect(page.getByRole("heading",{name:"Welcome, Asha."})).toBeVisible();
  const theme=page.getByLabel("Appearance");
  await theme.selectOption("light");
  await page.reload();
  await expect(theme).toHaveValue("light");
  expect(await theme.evaluate(node=>getComputedStyle(node).colorScheme)).toBe("light");
  const more=page.getByRole("button",{name:"More",exact:true});
  await more.focus();
  await page.keyboard.press("Enter");
  const menu=page.getByRole("dialog",{name:"Student workspace"});
  await expect(menu.getByRole("link",{name:"Opportunities"})).toBeVisible();
  await expect(menu.getByRole("link",{name:"Academic setup and roles"})).toHaveCount(0);
  await page.keyboard.press("Escape");
  await expect(more).toBeFocused();
  const open=page.getByRole("button",{name:"Ask AURA"});
  await open.click();
  const sheet=page.getByRole("dialog",{name:"Academic lookup"});
  await expect(sheet).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(open).toBeFocused();
  await open.press("Enter");
  await sheet.getByLabel("Look up").selectOption("My attendance");
  await sheet.getByRole("button",{name:"Check records"}).click();
  await expect(page).toHaveURL(/\/aura\?.*#aura-request-/);
  const receipt=page.locator(new URL(page.url()).hash);
  await expect(receipt).toBeFocused();
  await expect(receipt).toContainText("My attendance");
  await expect(receipt).toContainText("Model calls 0 · Tool operations 1");
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(320);
});
